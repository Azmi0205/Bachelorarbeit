function [t, y] = getLogSignal(logsout, signalName)
%GETLOGSIGNAL Extract time and data vectors for a named signal from a
%Simulink.SimulationData.Dataset (logsout).
%
%   [T, Y] = GETLOGSIGNAL(LOGSOUT, SIGNALNAME) looks up SIGNALNAME in
%   LOGSOUT (matching the logged/block signal name) and returns its time
%   vector T and data vector Y as column vectors of doubles.
    elem = logsout.get(signalName);
    if isempty(elem)
        error('getLogSignal:notFound', ...
            'Signal "%s" was not found in logsout.', signalName);
    end
    ts = elem.Values;
    % Handle the case where Values is itself a struct/bus with a single
    % leaf signal (rare, but keeps this robust for bus-logged elements).
    if isstruct(ts) || isa(ts, 'Simulink.SimulationData.Signal')
        error('getLogSignal:unsupportedFormat', ...
            'Signal "%s" resolved to a nested/bus type not handled here.', signalName);
    end
    t = double(ts.Time(:));
    y = double(ts.Data(:));
end
