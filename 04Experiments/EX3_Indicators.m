clear
clc

[logsout, T] = alignRampData('Measurements/'); % adjust to your data folder

%% Plot settings
commonXLim = [0.075, 1];
speedYLim  = [10, 225];
exportName = 'ramp_response_comparison';

%% Plot
fig = plotLoggedSignal1x1( ...
    logsout, ...
    { ...
        'USER_SPEED_MEAS_1', ...
        'USER_SPEED_MEAS_2', ...
        'USER_SPEED_REF' ...
    }, ...
    'XLabel', 'Time [s]', ...
    'YLabel', 'Angular Velocity [rad/s]', ...
    'Title', '', ...
    'Legend', { ...
        'Six-Step', ...
        'FOC', ...
        'Reference' ...
    }, ...
    'XLim', commonXLim, ...
    'YLim', speedYLim, ...
    'ShowXTickLabels', true, ...
    'ShowYTickLabels', true, ...
    'ExportName', exportName);

%% Ramp response metrics for the 300 ms ramp
tRampStart  = 0.100; % aligned ramp start, see alignRampData
rampEndTime = commonXLim(2); % end of the analysis window used for the plot

metrics1 = computeRampMetrics(T.time, T.USER_SPEED_MEAS_1, T.USER_SPEED_REF, ...
    tRampStart, 'EndTime', rampEndTime);
metrics2 = computeRampMetrics(T.time, T.USER_SPEED_MEAS_2, T.USER_SPEED_REF, ...
    tRampStart, 'EndTime', rampEndTime);

resultsTable = table( ...
    {'Six-Step'; 'FOC'}, ...
    [metrics1.riseTime;                metrics2.riseTime], ...
    [metrics1.settlingTime;            metrics2.settlingTime], ...
    [metrics1.overshootPct;            metrics2.overshootPct], ...
    [metrics1.avgAbsErrorDuringRise;   metrics2.avgAbsErrorDuringRise], ...
    [metrics1.avgAbsErrorDuringRisePct; metrics2.avgAbsErrorDuringRisePct], ...
    'VariableNames', ...
    {'Signal', 'RiseTime_s', 'SettlingTime_s', 'Overshoot_pct', ...
     'AvgAbsErrorDuringRise_radps', 'AvgAbsErrorDuringRise_pct'});

disp(resultsTable);
writetable(resultsTable, [exportName '_metrics.csv']);
