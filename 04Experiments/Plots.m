%% Compare measured speeds from two measurement pairs
%
% Figure 1:
%   Six-step: file 2
%   FOC:      file 5
%
% Figure 2:
%   Six-step: file 1
%   FOC:      file 4
%
% Each figure contains:
%   - Six-step measured speed
%   - FOC measured speed
%   - One common reference speed

clear;
clc;
close all;

%% Import all measurement files

folder = 'Measurements';
files = dir(fullfile(folder, '*.csv'));

if isempty(files)
    error( ...
        'compareMeasurements:noFiles', ...
        'No CSV files were found in the folder "%s".', ...
        folder);
end

% Sort the files alphabetically to obtain a reproducible file order.
[~, sortIndex] = sort({files.name});
files = files(sortIndex);

results = struct( ...
    'filename', {}, ...
    'data', {}, ...
    'table', {});

for k = 1:numel(files)
    fullPath = fullfile(files(k).folder, files(k).name);

    [results(k).data, results(k).table] = ...
        readUserSpeedCSVlog(fullPath);

    results(k).filename = files(k).name;
end

%% Display imported file order

fprintf('\nImported measurement files:\n');

for k = 1:numel(results)
    fprintf('  File %d: %s\n', k, results(k).filename);
end

fprintf('\n');

%% Verify that all required files are available

requiredFileCount = 5;

if numel(results) < requiredFileCount
    error( ...
        'compareMeasurements:notEnoughFiles', ...
        ['At least %d CSV files are required, but only %d files ' ...
         'were found in the folder "%s".'], ...
        requiredFileCount, numel(results), folder);
end

%% Define common axis limits

commonXLimLow = [1, 1.1];  % Time range in s
speedYLimLow = [16, 26];   % Angular velocity range in rad/s
commonXLimHigh = [1, 1.1];  % Time range in s
speedYLimHigh = [155, 205];   % Angular velocity range in rad/s



%% Comparison 1: files 2 and 5

sixStepIndex = 2;
focIndex = 5;

figFiles2And5 = createSpeedComparison( ...
    results, ...
    sixStepIndex, ...
    focIndex, ...
    commonXLimLow, ...
    speedYLimLow, ...
    'low_speed_comparison', ...
    'Files 2 and 5');

%% Comparison 2: files 1 and 4

sixStepIndex = 1;
focIndex = 4;

figFiles1And4 = createSpeedComparison( ...
    results, ...
    sixStepIndex, ...
    focIndex, ...
    commonXLimHigh, ...
    speedYLimHigh, ...
    'high_speed_comparison', ...
    'Files 1 and 4');


%% Local functions

function fig = createSpeedComparison( ...
    results, sixStepIndex, focIndex, ...
    commonXLim, speedYLim, exportName, comparisonName)
%CREATESPEEDCOMPARISON Create a single-axis speed comparison figure.
%
%   The figure contains the six-step measured speed, FOC measured speed,
%   and reference speed from the six-step measurement.

    %% Validate selected file indices

    nFiles = numel(results);

    if sixStepIndex < 1 || sixStepIndex > nFiles
        error( ...
            'createSpeedComparison:invalidSixStepIndex', ...
            ['The six-step file index %d is invalid. The imported ' ...
             'results contain %d files.'], ...
            sixStepIndex, nFiles);
    end

    if focIndex < 1 || focIndex > nFiles
        error( ...
            'createSpeedComparison:invalidFOCIndex', ...
            ['The FOC file index %d is invalid. The imported results ' ...
             'contain %d files.'], ...
            focIndex, nFiles);
    end

    %% Display selected files

    fprintf('%s:\n', comparisonName);

    fprintf('  Six-step measurement: file %d, %s\n', ...
        sixStepIndex, results(sixStepIndex).filename);

    fprintf('  FOC measurement:      file %d, %s\n\n', ...
        focIndex, results(focIndex).filename);

    %% Create combined dataset

    comparisonLogs = Simulink.SimulationData.Dataset;

    % Six-step measured speed.
    comparisonLogs = addCopiedSignal( ...
        comparisonLogs, ...
        results(sixStepIndex).data, ...
        'USER_SPEED_MEAS', ...
        'SIXSTEP_SPEED_MEAS');

    % FOC measured speed.
    comparisonLogs = addCopiedSignal( ...
        comparisonLogs, ...
        results(focIndex).data, ...
        'USER_SPEED_MEAS', ...
        'FOC_SPEED_MEAS');

    % Reference speed from the six-step file.
    % Only one reference is required because the reference signals from
    % both files are assumed to be equal.
    comparisonLogs = addCopiedSignal( ...
        comparisonLogs, ...
        results(sixStepIndex).data, ...
        'USER_SPEED_REF', ...
        'SPEED_REF');

    %% Create the single-axis comparison plot

    fig = plotLoggedSignal1x1( ...
        comparisonLogs, ...
        { ...
            'SIXSTEP_SPEED_MEAS', ...
            'FOC_SPEED_MEAS', ...
            'SPEED_REF' ...
        }, ...
        'XLabel', 'Time [s]', ...
        'YLabel', 'Angular Velocity [rad/s]', ...
        'Title', '', ...
        'Legend', { ...
            'Six-Step', ...
            'FOC', ...
            'Reference' ...
        }, ...
        'XLim', commonXLim, ...
        'YLim', speedYLim, ...
        'ShowXTickLabels', true, ...
        'ShowYTickLabels', true, ...
        'ExportName', exportName);
end


function destinationDataset = addCopiedSignal( ...
    destinationDataset, sourceDataset, sourceName, destinationName)
%ADDCOPIEDSIGNAL Copy and rename a signal in a Simulink dataset.
%
%   DESTINATIONDATASET = ADDCOPIEDSIGNAL(DESTINATIONDATASET,
%   SOURCEDATASET, SOURCENAME, DESTINATIONNAME) retrieves SOURCENAME
%   from SOURCEDATASET, creates an independent copy, renames it to
%   DESTINATIONNAME, and adds it to DESTINATIONDATASET.

    %% Retrieve source signal

    sourceSignal = sourceDataset.get(sourceName);

    if isempty(sourceSignal)
        error( ...
            'addCopiedSignal:signalNotFound', ...
            'Signal "%s" was not found in the source dataset.', ...
            sourceName);
    end

    if ~isprop(sourceSignal, 'Values')
        error( ...
            'addCopiedSignal:missingValues', ...
            'Signal "%s" does not have a Values property.', ...
            sourceName);
    end

    sourceValues = sourceSignal.Values;

    %% Create an independent copy

    if isa(sourceValues, 'timeseries')
        copiedValues = timeseries( ...
            sourceValues.Data, ...
            sourceValues.Time, ...
            'Name', destinationName);

        % Preserve metadata where available.
        copiedValues.TimeInfo.Units = ...
            sourceValues.TimeInfo.Units;

        copiedValues.DataInfo.Units = ...
            sourceValues.DataInfo.Units;

    elseif isa(sourceValues, 'timetable')
        copiedValues = sourceValues;

    else
        error( ...
            'addCopiedSignal:unsupportedType', ...
            ['Signal "%s" contains unsupported data of type "%s". ' ...
             'Expected a timeseries or timetable.'], ...
            sourceName, class(sourceValues));
    end

    %% Create and add the renamed signal

    copiedSignal = Simulink.SimulationData.Signal;
    copiedSignal.Name = destinationName;
    copiedSignal.Values = copiedValues;

    destinationDataset = destinationDataset.addElement( ...
        copiedSignal, destinationName);
end